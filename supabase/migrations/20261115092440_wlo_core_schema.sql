-- Create empty tables matching the active game/account schema.
CREATE TABLE public.user (
    userid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    password text NOT NULL,
    character1id integer,
    character2id integer,
    im integer NOT NULL DEFAULT 0,
    char_delete_code text,
    gmlevel integer NOT NULL DEFAULT 0 CHECK (gmlevel BETWEEN 0 AND 1)
);

CREATE TABLE public.characters (
    charid integer PRIMARY KEY,
    userid integer NOT NULL,
    slot integer NOT NULL,
    head integer NOT NULL,
    body integer NOT NULL,
    name text,
    name_clean text,
    nickname text,
    location_map integer NOT NULL,
    location_x integer NOT NULL,
    location_y integer NOT NULL,
    haircolor integer NOT NULL,
    skincolor integer NOT NULL,
    clothingcolor integer NOT NULL,
    eyecolor integer NOT NULL,
    gold integer NOT NULL,
    element integer NOT NULL,
    rebirth integer NOT NULL,
    job integer NOT NULL,
    online integer NOT NULL
);

CREATE TABLE public.charactersextdata (
    charid integer PRIMARY KEY,
    settings text,
    friends text,
    guild text,
    mail text
);

CREATE TABLE public.chartent (
    charid integer PRIMARY KEY,
    locked integer,
    enlarged integer,
    tenttype integer,
    floor1color integer,
    floor1wallpaper integer,
    floor2color integer,
    floor2wallpaperr integer
);

CREATE TABLE public.charquest (
    pri_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charid integer NOT NULL,
    quest_started integer,
    quest_pos integer
);

CREATE TABLE public.charunlocks (
    pri_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charid integer NOT NULL,
    maploc integer,
    clickid integer
);

CREATE TABLE public.inventory (
    pri_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invidx integer NOT NULL,
    charid integer,
    storid integer,
    itemid integer,
    dmg integer,
    qty integer,
    pos integer,
    socketid integer,
    bombid integer,
    sewID integer,
    forge integer
);

CREATE TABLE public.stats (
    pri_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statidx integer NOT NULL,
    charid integer,
    statid integer,
    statusup integer,
    potential integer
);

CREATE TABLE public.mall_orders (
    orderid text PRIMARY KEY,
    requestid text NOT NULL,
    userid integer NOT NULL,
    charid integer NOT NULL,
    itemid integer NOT NULL,
    price integer NOT NULL,
    status text NOT NULL,
    createdat text NOT NULL,
    deliveredat text,
    UNIQUE (userid, requestid)
);

CREATE TABLE public.mall_reviews (
    userid integer NOT NULL,
    itemid integer NOT NULL,
    rating integer NOT NULL,
    reviewtext text NOT NULL,
    createdat text NOT NULL,
    UNIQUE (userid, itemid)
);

CREATE TABLE public.mall_newsletter (
    email text PRIMARY KEY,
    subscribedat text NOT NULL
);

CREATE INDEX idx_characters_userid_charid ON public.characters (userid, charid);
CREATE INDEX idx_stats_charid ON public.stats (charid);
CREATE INDEX idx_inventory_charid_storid ON public.inventory (charid, storid);

